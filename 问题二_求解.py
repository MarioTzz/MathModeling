def run_optimized_smoke(config: dict, output_root: Path, overwrite: bool) -> dict:
    """P1真实文件纵向切片：每类1个拟合、1个留出。"""
    prepare_generated_directory(output_root, overwrite)
    optimized = config["optimized"]
    metadata = pd.read_csv(ROOT / "模型适配数据集/q1/files.csv", keep_default_na=False)
    training = metadata[(metadata.domain.eq("source")) & metadata.split.eq("train")]
    fit_ids, hold_ids = [], []
    for label in config["class_order"]:
        ids = sorted(training.loc[training.label.eq(label), "file_id"])[:2]
        if len(ids) != 2:
            raise ValueError(f"{label} 缺少两个独立训练文件")
        fit_ids.append(ids[0])
        hold_ids.append(ids[1])
    q1 = json.loads((ROOT / "results/q1/summary.json").read_text(encoding="utf-8"))
    windows = extract_multiband_windows(
        ROOT, training, q1["parameters"], optimized, file_ids=fit_ids+hold_ids)
    all_sets = feature_sets(optimized)
    files = aggregate_file_medians(windows, all_sets["multiband_both"])
    features = median_columns(all_sets["multiband_spin_half"])
    local_config = dict(optimized, n_estimators=11)
    model = fit_extra_trees(files[files.file_id.isin(fit_ids)], features,
                            {"min_samples_leaf": 1, "max_features": "sqrt"}, local_config)
    hold = files[files.file_id.isin(hold_ids)]
    prediction = optimized_prediction_table(model, hold)
    metrics, detail, confusion = classification_metrics(
        prediction.true_label, prediction.prediction)
    save_optimized_model(model, output_root / "model.json", output_root / "model_arrays.npz")
    error = float(np.max(np.abs(model.scores(hold) - scores_from_export(
        output_root / "model.json", output_root / "model_arrays.npz", hold))))
    if error > 1e-12:
        raise ValueError("小样本导出状态重建失败")
    save_csv(windows, output_root / "window_features.csv")
    save_csv(files, output_root / "file_medians.csv")
    save_csv(prediction, output_root / "file_predictions.csv")
    save_csv(detail, output_root / "per_class_metrics.csv")
    save_csv(confusion.rename_axis("true_label").reset_index(), output_root / "confusion.csv")
    summary = {"mode": "optimized_smoke", "fit_file_ids": fit_ids,
               "hold_file_ids": hold_ids, "metrics": metrics,
               "feature_family": "multiband_spin_half", "features": len(features),
               "export_reconstruction_error": error,
               "test_or_validation_files_used": 0, "target_files_used": 0}
    write_json(output_root / "summary.json", summary)
    return summary


