def run_optimized(config: dict, output_root: Path | None, overwrite: bool,
                  no_plots: bool) -> dict:
    started = time.perf_counter()
    if output_root is None:
        data_dir, result_dir, figure_dir = (
            ROOT / "模型适配数据集/q2_optimized", ROOT / "results/q2_optimized",
            ROOT / "figures/q2_optimized")
    else:
        base = output_root.resolve()
        data_dir, result_dir, figure_dir = base / "data", base / "results", base / "figures"
    for directory in [data_dir, result_dir, figure_dir]:
        prepare_generated_directory(directory, overwrite)
    optimized = config["optimized"]
    metadata = pd.read_csv(ROOT / "模型适配数据集/q1/files.csv", keep_default_na=False)
    source = metadata[metadata.domain.eq("source")].copy()
    split_counts = source.split.value_counts()
    if [int(split_counts.get(name, 0)) for name in ["train", "validation", "test"]] != [70, 23, 23]:
        raise ValueError("原有源域划分不是70/23/23")
    q1 = json.loads((ROOT / "results/q1/summary.json").read_text(encoding="utf-8"))
    q1_parameters = q1["parameters"]
    if q1["chosen_band_hz"] != optimized["single_band_hz"] \
            or q1["chosen_revolutions"] != optimized["window_revolutions"]:
        raise ValueError("优化模型的Q1频带/窗口接口与上游不一致")

    print("1/7 从116个源域MAT提取三频带故障阶次与包络特征", flush=True)
