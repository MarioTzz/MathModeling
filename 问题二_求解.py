    save_csv(files, data_dir / "source_multiband_file_medians.csv")
    train = files[files.split.eq("train")].copy()
    validation = files[files.split.eq("validation")].copy()
    development = files[files.split.isin(["train", "validation"])].copy()
    test = files[files.split.eq("test")].copy()

    print("2/7 仅用训练70文件为五个特征家族分别调参，再在验证集择优", flush=True)
    selection_rows, train_cv_rows, train_summary_rows, validation_predictions = [], [], [], []
    choices = {}
    for family in optimized["feature_family_order"]:
        features = median_columns(all_sets[family])
        parameters, detailed, table = tune_extra_trees(
            train, features, optimized, int(optimized["train_cv_folds"]))
        model = fit_extra_trees(train, features, parameters, optimized)
        predictions = optimized_prediction_table(model, validation)
        metrics, _, _ = classification_metrics(predictions.true_label, predictions.prediction)
        selection_rows.append({"feature_family": family, **metrics,
                               **parameters, "n_features": len(features)})
        train_cv_rows.append(detailed.assign(feature_family=family))
        train_summary_rows.append(table.assign(feature_family=family))
        validation_predictions.append(predictions.assign(feature_family=family))
        choices[family] = (model, parameters)
    validation_table = pd.DataFrame(selection_rows)
    validation_table["tie_preference"] = validation_table.feature_family.eq(
        optimized["feature_family_tiebreak"]).astype(int)
    chosen = validation_table.sort_values(
        ["accuracy", "macro_f1", "balanced_accuracy", "normal_recall", "tie_preference"],
        ascending=[False, False, False, False, False], kind="stable").iloc[0]
