def prepare_generated_directory(path: Path, overwrite: bool, marker_name=".q2-generated"):
    path = path.resolve()
    if not path.is_relative_to(ROOT):
        raise ValueError("输出必须位于项目目录")
    marker = path / marker_name
    if path.exists() and any(path.iterdir()) and (not overwrite or not marker.exists()):
        raise FileExistsError(f"非空输出目录不可覆盖: {path}")
    path.mkdir(parents=True, exist_ok=True)
    marker.write_text("Generated by 问题二_求解.py; source data are read-only.\n", encoding="utf-8")


def read_inputs(config):
    metadata = pd.read_csv(ROOT / "模型适配数据集/q1/files.csv", keep_default_na=False)
    frames = {
        name: pd.read_csv(ROOT / relative, keep_default_na=False)
        for name, relative in config["representations"].items()
    }
    source_ids = set(metadata.loc[metadata.domain.eq("source"), "file_id"])
    for name, frame in frames.items():
        if frame[["file_id", "window_index"]].duplicated().any():
            raise ValueError(f"{name} 存在重复窗口键")
        if not np.isfinite(frame.loc[frame.file_id.isin(source_ids)].select_dtypes("number")).all().all():
            raise ValueError(f"{name} 源域数值含非有限值")
    return metadata, frames


def metric_rows(model_name, representation, split, predictions, aggregation="mean_score"):
    column = {"mean_score": "prediction", "median_score": "median_prediction",
              "majority_vote": "majority_prediction"}[aggregation]
    metrics, detail, confusion = classification_metrics(
        predictions.true_label, predictions[column])
    return ({"model": model_name, "representation": representation, "split": split,
             "aggregation": aggregation, **metrics}, detail, confusion)


def choose_representation(validation_table: pd.DataFrame, config: dict):
    candidates = validation_table[
        validation_table.model.eq(config["main_model"])
        & validation_table.aggregation.eq("mean_score")].copy()
    candidates["tie_preference"] = candidates.representation.eq(
        config["representation_tiebreak"]).astype(int)
    chosen = candidates.sort_values(
        ["macro_f1", "balanced_accuracy", "normal_recall", "tie_preference"],
        ascending=[False, False, False, False], kind="stable").iloc[0]
    return str(chosen.representation)


def noise_stress(frame, metadata, model, representation, q1_config, q2_config):
    """式(2.30)：源测试原始信号加噪后重跑 Q1 完整特征链。"""
    test_meta = metadata[(metadata.domain.eq("source")) & (metadata.split.eq("test"))]
    baseline_predictions, _ = aggregate_predictions(model, frame[frame.split.eq("test")])
    baseline_map = baseline_predictions.set_index("file_id").prediction
    turns = q1_config["chosen_revolutions"] if representation == "equal_revolutions" else None
    band = q1_config["chosen_band_hz"]
    rows, feature_parts = [], []
    recompute_error = None
    for level in q2_config["noise_relative_rms"]:
        parts = []
        for metadata_row in test_meta.to_dict("records"):
            record = load_record(ROOT, metadata_row)
            if level > 0:
                rng = np.random.default_rng(deterministic_noise_seed(
                    q2_config["seed"], record.file_id, level))
                noise = rng.normal(size=len(record.centered))
                noise *= level * np.sqrt(np.mean(record.centered ** 2)) \
                    / np.sqrt(np.mean(noise ** 2))
                record = Record(record.metadata, record.centered + noise,
                                record.fs, record.rotation_hz)
            envelope = prepare_record(record, band, q1_config["parameters"])
            changed, _ = window_features(record, envelope, turns, q1_config["parameters"])
            parts.append(changed)
        changed = pd.concat(parts, ignore_index=True)
        if level == 0:
            original = frame[frame.split.eq("test")].sort_values(
                ["file_id", "window_index"])
            check = changed.sort_values(["file_id", "window_index"])
            if list(original.file_id) != list(check.file_id):
                raise ValueError("噪声零基线与导出窗口键不一致")
            from utils.q1_model import FEATURES
            recompute_error = float(np.max(np.abs(
                original[FEATURES].to_numpy() - check[FEATURES].to_numpy())))
            if recompute_error > 1e-9:
                raise ValueError(f"零噪声重算未复现 Q1 特征: {recompute_error}")
        predictions, _ = aggregate_predictions(model, changed)
        metrics, _, _ = classification_metrics(predictions.true_label, predictions.prediction)
        retention = float(np.mean(predictions.set_index("file_id").prediction ==
                                  baseline_map.loc[predictions.file_id].to_numpy()))
        snr_db = None if level == 0 else float(-20 * np.log10(level))
        rows.append({"perturbation": "white_noise", "level": level,
                     "snr_db": snr_db, "prediction_retention": retention, **metrics})
        feature_parts.append(changed.assign(noise_relative_rms=level))
    return pd.DataFrame(rows), recompute_error


