    export_error = float(np.max(np.abs(
        model.scores(test) - scores_from_export(
            data_dir / "source_classifier.json", data_dir / "source_classifier_arrays.npz",
            test))))
    if export_error > 1e-12:
        raise ValueError("导出树模型的跨进程状态分数不能复现")
    save_csv(pd.DataFrame({"feature": features}), result_dir / "selected_features_final.csv")

    print("4/7 从原始MAT重算增益和噪声扰动", flush=True)
    baseline = predictions.set_index("file_id").prediction
